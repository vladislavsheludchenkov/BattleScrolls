// Extracts static display donors from the addon (the single source of truth)
// into a TypeScript module the viewer imports.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "src/shared/icon_overrides.ts");

function extract(source, table, exported, localized = false) {
    const lua = readFileSync(resolve(root, "..", source), "utf8");
    const match = lua.match(new RegExp(`local ${table} = \\{\\n([\\s\\S]*?)\\n\\}`));
    if (!match) throw new Error(`${table} not found in ${source}`);
    const lines = [];
    for (const raw of match[1].split("\n")) {
        const entry = raw.match(localized
            ? /^\s*\[(\d+)\]\s*=\s*\{\s*([a-z]+)\s*=\s*(\d+)\s*\},?\s*(?:--\s*(.*))?$/
            : /^\s*\[(\d+)\]\s*=\s*(\d+),?\s*(?:--\s*(.*))?$/);
        if (!entry) continue;
        const note = entry[localized ? 4 : 3];
        const comment = note ? ` // ${note.trim()}` : "";
        const value = localized ? `{ ${entry[2]}: ${entry[3]} }` : entry[2];
        lines.push(`  ${entry[1]}: ${value},${comment}`);
    }
    if (lines.length === 0) throw new Error(`no override entries parsed in ${table}`);
    console.log(`${exported}: ${lines.length} entries`);
    return `// ${source} (${table}).
export const ${exported}: Record<number, ${localized ? "Partial<Record<string, number>>" : "number"}> = {
${lines.join("\n")}
};
`;
}

writeFileSync(target, "// Generated by scripts/gen-icon-overrides.mjs. Do not edit.\n"
    + extract("BattleScrolls/ui/journal/utils.lua", "abilityIconAbilityIdOverrides", "ICON_DONORS")
    + "\n" + extract("BattleScrolls/core/utils.lua", "abilityNameAbilityIdOverrides", "NAME_DONORS")
    + "\n" + extract("BattleScrolls/core/utils.lua", "localizedAbilityNameAbilityIdOverrides", "LOCALIZED_NAME_DONORS", true));
