const STRINGS = { en, de, es, fr, jp, ru, zh };

/** English read through LangTable: every lookup falls back to it. */
const EN: LangTable = en;
/** Widened views for the runtime lookups, whose language code is unvalidated input. */
const TABLE_BY_CODE: Record<string, LangTable | undefined> = STRINGS;
const LOCALE_BY_CODE: Record<string, string | undefined> = LOCALES;

let cur: LangTable = en;
let curLocale: string = LOCALES.en;

export function setLang(lang: string): void {
  cur = TABLE_BY_CODE[lang] || en;
  curLocale = LOCALE_BY_CODE[lang] || LOCALES.en;
}

export function currentLocale(): string {
  return curLocale;
}

/** Translates a key, substituting {0}/{1}/... with args. */
export function t(key: StringKey, ...args: (string | number)[]): string {
  let s = cur[key] ?? EN[key] ?? key;
  for (let i = 0; i < args.length; i++) {
    s = s.replaceAll(`{${i}}`, String(args[i]));
  }
  return s;
}

/** Translates from a keyed sub-table (roles, races, quality, ...). */
export function tm(table: TableName, key: number | undefined, fallback: string): string {
  // An undefined key missed every table under the old `map[undefined]` lookup too.
  if (key === undefined) return fallback;
  const enMap = EN[table];
  const map = cur[table] ?? enMap;
  return (map && map[key]) ?? (enMap && enMap[key]) ?? fallback;
}
