/**
 * Keys whose English value is a plain string: everything `t()` can look up.
 * Derived from `en`, so a mistyped key is a compile error at the call site.
 */
export type StringKey = {
  [K in keyof typeof en]: (typeof en)[K] extends string ? K : never;
}[keyof typeof en];

/** Keys whose English value is a lookup sub-table: everything `tm()` can read. */
export type TableName = {
  [K in keyof typeof en]: (typeof en)[K] extends string ? never : K;
}[keyof typeof en];

/** A sub-table maps a game enum value (role, race, trait, slot index, ...) to a label. */
type SubTable = Record<number, string>;

/**
 * One language's strings. Every entry is optional because English fills any gap
 * at lookup time — but a key that English does not define is a compile error.
 */
type LangTable = Partial<Record<StringKey, string>> & Partial<Record<TableName, SubTable>>;

